#!/usr/bin/env python3
"""Import a locally obtained supplier WaveformData.c into ignored build inputs.

The generated bytes belong to the supplier. This script verifies the exact
reference file used by this project; it does not download or redistribute it.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
EXPECTED_BYTES = 74472
EXPECTED_SHA256 = "48b099be4e104e55052baafb70fac10f2c2fa225e83bd2f67ec18452fa5b7a86"
ARRAY = re.compile(r"\bg_WaveformData\s*\[\s*\]\s*=\s*\{(?P<body>.*?)\}\s*;", re.S)
BYTE = re.compile(r"0x([0-9a-fA-F]{2})\b")


def extract(source: Path) -> bytes:
    match = ARRAY.search(source.read_text(encoding="utf-8", errors="replace"))
    if match is None:
        raise ValueError("Could not find g_WaveformData[] in the supplied C file")
    data = bytes(int(value, 16) for value in BYTE.findall(match.group("body")))
    digest = hashlib.sha256(data).hexdigest()
    if len(data) != EXPECTED_BYTES or digest != EXPECTED_SHA256:
        raise ValueError(
            f"This is not the verified waveform: bytes={len(data)}, SHA256={digest}; "
            f"expected {EXPECTED_BYTES} and {EXPECTED_SHA256}"
        )
    return data


def render_header(data: bytes) -> str:
    rows = ["    " + ", ".join(f"0x{byte:02x}" for byte in data[i:i + 16]) + ","
            for i in range(0, len(data), 16)]
    return "\n".join([
        "/* Locally generated from the supplier's WaveformData.c.",
        " * Supplier rights retained. Do not commit or redistribute this file.",
        f" * SHA256 {EXPECTED_SHA256}",
        " */",
        "#ifndef ET014_WAVEFORM_DATA_H",
        "#define ET014_WAVEFORM_DATA_H",
        "#include <stdint.h>",
        f"static const uint8_t et014_waveform_data[{EXPECTED_BYTES}] = {{",
        *rows,
        "};",
        "#endif",
        "",
    ])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="path to your supplier WaveformData.c")
    args = parser.parse_args()
    data = extract(args.source)
    header = ROOT / "components/et014/src/et014_waveform_data.h"
    fixture = ROOT / "tests/fixtures/vendor-waveform.bin"
    header.parent.mkdir(parents=True, exist_ok=True)
    fixture.parent.mkdir(parents=True, exist_ok=True)
    header.write_text(render_header(data), encoding="utf-8", newline="\n")
    fixture.write_bytes(data)
    print(f"Imported {len(data)} bytes; SHA256 {EXPECTED_SHA256}")
    print(f"Generated local-only inputs: {header.relative_to(ROOT)}, {fixture.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
